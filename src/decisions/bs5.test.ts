/**
 * The text of an HTML fragment with its entities resolved.
 *
 * @param html the escaped text
 */
function unescaped(html: string | undefined): string | undefined {
  return html
    ?.replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&");
}

/** A request the route refuses, the code the protocol names for it and the key of its explanation in admin/i18n. */
interface Fault {
  name: string;
  method: "GET" | "POST";
  fields: Record<string, string>;
  code: string;
  key: string;
}

